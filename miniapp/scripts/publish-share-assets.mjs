import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Materialize only the deliberately selected public cover images. Hashed names
// remain immutable; previous covers stay available for already-sent cards.
const args = process.argv.slice(2)
if (args.some(arg => arg !== '--check')) throw new Error('Usage: node scripts/publish-share-assets.mjs [--check]')
const check = args.includes('--check')
const miniappRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const staticRoot = path.join(miniappRoot, 'src/static')
const outputRoot = path.resolve(miniappRoot, '../website-react/public/assets/miniapp-share')
const manifestPath = path.join(miniappRoot, 'src/data/shareAssets.js')
const files = ['editorial/course-classroom.jpg', 'editorial/course-team.jpg', 'editorial/course-family.jpg']
for (const directory of ['share', 'studio-preview/posters']) {
  for (const entry of await readdir(path.join(staticRoot, directory), { withFileTypes: true })) {
    if (entry.isFile() && /\.(?:png|jpe?g)$/i.test(entry.name)) files.push(`${directory}/${entry.name}`)
  }
}
files.sort()
if (!check) await mkdir(outputRoot, { recursive: true })
const manifest = {}
let bytes = 0
for (const relative of files) {
  const source = await readFile(path.join(staticRoot, relative))
  const extension = path.extname(relative).toLowerCase()
  const isJpeg = extension === '.jpg' || extension === '.jpeg'
  assert.ok(isJpeg ? source[0] === 0xff && source[1] === 0xd8 : source.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])), `Unexpected cover format: ${relative}`)
  const digest = createHash('sha256').update(source).digest('hex').slice(0, 12)
  const basename = path.basename(relative, path.extname(relative)).replace(/[^a-zA-Z0-9_-]/g, '-')
  const filename = `${basename}-${digest}${isJpeg ? '.jpg' : '.png'}`
  const target = path.join(outputRoot, filename)
  let published
  try { published = await readFile(target) } catch (error) { if (error.code !== 'ENOENT') throw error }
  if (published) assert.ok(published.equals(source), `Immutable public cover differs: ${filename}`)
  else if (check) throw new Error(`Missing published share cover: ${filename}`)
  else await writeFile(target, source, { flag: 'wx', mode: 0o644 })
  manifest[`/static/${relative}`] = `/assets/miniapp-share/${filename}`
  bytes += source.length
}
const json = `// Generated by scripts/publish-share-assets.mjs. Preserve historical public covers.\nexport default ${JSON.stringify(manifest, null, 2)}\n`
if (check) assert.equal(await readFile(manifestPath, 'utf8'), json, 'Share asset manifest is stale; regenerate it')
else await writeFile(manifestPath, json, { mode: 0o644 })
console.log(`${check ? 'Verified' : 'Published'} ${files.length} public share covers (${bytes} bytes); historical covers retained`)
